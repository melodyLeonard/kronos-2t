    private static func scalars(_ ranges: [ClosedRange<UInt32>]) -> [String] {
        var out: [String] = []
        for r in ranges {
            for v in r {
                guard let s = Unicode.Scalar(v), s.properties.isEmoji else { continue }
                if s.properties.isEmojiPresentation {
                    out.append(String(s))
                } else if v > 0xFF, s.properties.isEmojiModifierBase || s.properties.isEmoji {
                    // Text-default symbols (☺ ✌ ❤) need VS16 to render as emoji.
                    out.append(String(s) + "\u{FE0F}")
                }
            }
        }
        return out
    }

